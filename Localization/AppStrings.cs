using System.ComponentModel;
using System.Globalization;

namespace yChicaTube.Localization;

public class LocalizationManager : INotifyPropertyChanged
{
    private static readonly Lazy<LocalizationManager> _instance = new(() => new LocalizationManager());
    public static LocalizationManager Instance => _instance.Value;

    public event PropertyChangedEventHandler? PropertyChanged;

    private string _currentLanguage = "pt";

    public string CurrentLanguage
    {
        get => _currentLanguage;
        set
        {
            if (_currentLanguage != value)
            {
                _currentLanguage = NormalizeLanguage(value);
                PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(null));
            }
        }
    }

    public string this[string key] => Get(key);

    public LocalizationManager()
    {
        // Detecta automaticamente o idioma do sistema operativo
        var systemLang = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLowerInvariant();
        _currentLanguage = NormalizeLanguage(systemLang);
    }

    public static string NormalizeLanguage(string langCode)
    {
        if (string.IsNullOrWhiteSpace(langCode)) return "pt";
        var lower = langCode.ToLowerInvariant();
        if (lower.StartsWith("es")) return "es";
        if (lower.StartsWith("en")) return "en";
        if (lower.StartsWith("pt")) return "pt";
        return "en"; // Fallback internacional
    }

    public string Get(string key, params object[] args)
    {
        if (string.IsNullOrWhiteSpace(key)) return string.Empty;

        if (Translations.TryGetValue(_currentLanguage, out var dict) && dict.TryGetValue(key, out var text))
        {
            return args.Length > 0 ? string.Format(text, args) : text;
        }

        // Fallback para Português ou Inglês
        if (Translations["pt"].TryGetValue(key, out var fallbackPt))
        {
            return args.Length > 0 ? string.Format(fallbackPt, args) : fallbackPt;
        }

        return key;
    }

